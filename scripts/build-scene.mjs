// Builds paris3d.js (one classic script) from the scene's ES modules in paris3d/.
// The modules are the source (one file per object); the page loads the built file, which also works from file://
// (browsers refuse ES modules there) and costs one request instead of 33. Run: pnpm run scene
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'paris3d');
const out = join(root, 'paris3d.js');

// every module, by its path relative to paris3d/ ('city/scene.js')
const files = [];
(function walk(dir) { for (const f of readdirSync(dir)) { const p = join(dir, f); if (statSync(p).isDirectory()) walk(p); else if (f.endsWith('.js')) files.push(relative(src, p).split('\\').join('/')); } })(src);
const code = Object.fromEntries(files.map((f) => [f, readFileSync(join(src, f), 'utf8').replace(/\r\n/g, '\n')]));

// dependencies: relative imports only ('three' is the page's global THREE in the built file)
const IMPORT = /^import\s+(?:[^'"]*?\s+from\s+)?'([^']+)';\s*$/gm;
const deps = Object.fromEntries(files.map((f) => [f, [...code[f].matchAll(IMPORT)].map((m) => m[1]).filter((s) => s.startsWith('.')).map((s) => posix.normalize(posix.join(posix.dirname(f), s)))]));
for (const f of files) for (const d of deps[f]) if (!code[d]) throw new Error(`${f} imports missing ${d}`);

// dependencies first (top-level initialisers may read another module's values), index.js last
const order = [], seen = new Set();
(function visit(f, stack = []) {
  if (seen.has(f)) return; if (stack.includes(f)) return;   // a cycle only links functions, which are hoisted
  for (const d of deps[f]) visit(d, stack.concat(f));
  seen.add(f); order.push(f);
})('index.js');
const unused = files.filter((f) => !seen.has(f));
if (unused.length) throw new Error('modules not reachable from index.js: ' + unused.join(', '));

// index.js opens with the scene's header comment: keep it at the top of the built file
const header = (code['index.js'].match(/^(\/\*[\s\S]*?\*\/\s*)+/) || [''])[0];
// the names a module exports: `export function f`, `export async function f`, `export var a = 1, b = [..]` (top-level
// declarators split on depth-0 commas)
function exported(s) {
  const names = [];
  for (const m of s.matchAll(/^export (?:async )?function (\w+)/gm)) names.push(m[1]);
  for (const m of s.matchAll(/^export var /gm)) {
    let i = m.index + m[0].length, depth = 0, q = null, start = i;
    for (; i < s.length; i++) {
      const ch = s[i];
      if (q) { if (ch === '\\') i++; else if (ch === q) q = null; continue; }
      if (ch === '/' && s[i + 1] === '/') { i = s.indexOf('\n', i); continue; }
      if (ch === '/' && s[i + 1] === '*') { i = s.indexOf('*/', i) + 1; continue; }
      if (ch === "'" || ch === '"' || ch === '`') q = ch;
      else if ('([{'.includes(ch)) depth++;
      else if (')]}'.includes(ch)) depth--;
      else if (depth === 0 && (ch === ',' || ch === ';')) { names.push(s.slice(start, i).trim().match(/^\w+/)[0]); start = i + 1; if (ch === ';') break; }
    }
  }
  return names;
}
// each module runs in its own scope (its helpers can't collide with another module's)
// and returns its exports as an object, kept per module in __mods: an import reads the module it names, so two modules may
// export the same name (pal, pointSprite...) as in ES modules
const REL_IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'(\.[^']+)';\s*$/gm;
const body = order.map((f) => {
  let s = f === 'index.js' ? code[f].slice(header.length) : code[f];
  const names = exported(s);
  s = s.replace(REL_IMPORT, (_, list, from) => 'var { ' + list.split(',').map((n) => n.trim()).filter(Boolean).map((n) => {
    const [a, b = a] = n.split(/\s+as\s+/); return a === b ? a : a + ': ' + b;
  }).join(', ') + " } = __mods['" + posix.normalize(posix.join(posix.dirname(f), from)) + "'];");
  s = s.replace(IMPORT, '').replace(/^export (async function|function|var) /gm, '$1 ').replace(/^\s*\n/, '');
  if (/^\s*(export|import)\b/m.test(s)) throw new Error(`${f}: an export/import form the build doesn't handle`);
  const inner = s.trimEnd() + (names.length ? `\nreturn { ${names.join(', ')} };` : '');
  return `  // ---- ${f}\n  __mods['${f}'] = (function () {\n` + inner.split('\n').map((l) => (l ? '    ' + l : l)).join('\n') + '\n  })();';
}).join('\n\n');

const built = `/* GENERATED by scripts/build-scene.mjs from paris3d/ — edit the modules there, then run: pnpm run scene */\n` + header +
  `(function () {\n  'use strict';\n  var T = window.THREE;\n  if (!T) return;\n  var __mods = {};\n\n${body}\n})();\n`;
writeFileSync(out, built);
console.log(`paris3d.js: ${order.length} modules, ${built.length} bytes`);
