// Regenerates trajectory-data.js — real weekly commit counts on each repo's
// default branch, from WEEK_START to the current week, via the GitHub API (gh).
// Runs before every push to main (.githooks/pre-push); `pnpm run trajectory`
// runs it by hand.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const WEEK_START = '2025-12-01'; // a Monday
// key → GitHub repo; display metadata (name, role, colour) lives in trajectory.js
export const REPOS = {
  pages: 'kouji-dev/pages',
  acta: 'kouji-dev/acta',
  asda: 'kouji-dev/asda',
  'kouji-ui': 'kouji-dev/kouji-ui',
  orrery: 'kouji-dev/orrery',
  vortex: 'kouji-dev/vortex',
  preesm: 'kouji-dev/preesm',
};

const WK = 7 * 864e5;

// Weeks from WEEK_START through the week holding `now`, inclusive.
export function weekCount(now) {
  return Math.floor((now - Date.parse(WEEK_START + 'T00:00:00Z')) / WK) + 1;
}

// ISO date strings → per-week counts; dates outside the window are dropped.
export function bucket(dates, n) {
  const t0 = Date.parse(WEEK_START + 'T00:00:00Z');
  const m = new Array(n).fill(0);
  for (const d of dates) {
    const i = Math.floor((Date.parse(d) - t0) / WK);
    if (i >= 0 && i < n) m[i]++;
  }
  return m;
}

function authorDates(repo) {
  // author date, not committer date: rebases and merges rewrite the latter
  const out = execFileSync('gh', ['api', '--paginate',
    `repos/${repo}/commits?since=${WEEK_START}T00:00:00Z&per_page=100`,
    '--jq', '.[].commit.author.date'], { encoding: 'utf8', maxBuffer: 64 << 20 });
  return out.split('\n').filter(Boolean);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const n = weekCount(Date.now());
  const m = {};
  for (const [key, repo] of Object.entries(REPOS)) m[key] = bucket(authorDates(repo), n);
  const data = { weekStart: WEEK_START, weekCount: n, m };
  writeFileSync(new URL('../trajectory-data.js', import.meta.url),
    '// GENERATED by scripts/trajectory-data.mjs — do not edit.\n' +
    'window.TRAJECTORY_DATA = ' + JSON.stringify(data) + ';\n');
  const total = Object.values(m).flat().reduce((a, b) => a + b, 0);
  console.log(`trajectory-data.js: ${n} weeks, ${total} commits`);
}
