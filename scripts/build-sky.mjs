// Regenerates sky.js from the painting in design/Minimal.dc.html (between the
// <!--PT--> markers). `pnpm run sky` after every design sync.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// the painting's {{ holes }} → the values home.js starts from
const DEFAULTS = { sky: 'night', fount: 'on', sparkle: '0', gust: '0', paused: '0', focus: '' };

export function build(designHtml) {
  const a = designHtml.indexOf('<!--PT-->'), b = designHtml.indexOf('<!--/PT-->');
  if (a < 0 || b < a) throw new Error('painting markers <!--PT--> … <!--/PT--> not found');
  return designHtml.slice(a + 9, b)
    .replace(/\{\{ (\w+) \}\}/g, (_, k) => {
      if (!(k in DEFAULTS)) throw new Error('unknown painting hole {{ ' + k + ' }}');
      return DEFAULTS[k];
    });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = build(readFileSync('design/Minimal.dc.html', 'utf8'));
  writeFileSync('sky.js',
    '// GENERATED by scripts/build-sky.mjs from design/Minimal.dc.html (the Eiffel Tower painting); home.js injects it into .sky.\n' +
    '// A script rather than a fetched fragment so it also loads from file://.\n' +
    'window.SKY_SVG = ' + JSON.stringify(out) + ';\n');
  console.log('sky.js:', out.length, 'bytes');
}
