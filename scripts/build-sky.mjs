// Regenerates sky.js from the painting in design/Main.dc.html (between the
// <!--PT--> markers) and the skins' moments / firework shapes (between the
// /*SKINDATA*/ markers). `pnpm run sky` after every design sync.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// the {{ holes }} on the .pt root → the values home.js starts from (it rewrites them all)
const DEFAULTS = {
  sky: 'night', fount: 'on', sparkle: '0', gust: '0', paused: '0', focus: '', ptStyle: '',
  season: '', phase: '1', wx: '', event: '', moment: '', fw: '0', shape: '', slot: '', corner: 'tl',
  ny: '', day: '', year: '', gl: '0',
};

function between(src, open, close) {
  const a = src.indexOf(open), b = src.indexOf(close, a + 1);
  if (a < 0 || b < a) throw new Error(open + ' … ' + close + ' markers not found');
  return src.slice(a + open.length, b);
}

export function build(designHtml) {
  const p = between(designHtml, '<!--PT-->', '<!--/PT-->');
  const end = p.indexOf('>') + 1;
  const root = p.slice(0, end).replace(/\{\{ (\w+) \}\}/g, (_, k) => {
    if (!(k in DEFAULTS)) throw new Error('unknown painting hole {{ ' + k + ' }}');
    return DEFAULTS[k];
  });
  // holes inside the painting become hooks home.js fills: an attribute → data-h-<attr>, text → <tspan data-h>
  const body = p.slice(end)
    .replace(/ ([\w-]+)="\{\{ (\w+) \}\}"/g, ' $1="" data-h-$1="$2"')
    .replace(/\{\{ (\w+) \}\}/g, '<tspan data-h="$1"></tspan>');
  return root + body;
}

// every class the painting CSS shows or hides with display: home.js marks the hidden ones
// .off so their animations stop (Chrome keeps ticking CSS animations inside display:none SVG)
export function toggles(designHtml) {
  const css = between(designHtml, '/*PAINT*/', '/*/PAINT*/').replace(/@keyframes[^{]*\{([^{}]*\{[^}]*\})*[^}]*\}/g, '');
  const out = new Set();
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*display:[^{}]*)\}/g)) {
    for (const sel of m[1].replace(/^\s*@media[^{]*/, '').split(',')) {
      const last = sel.trim().split(/\s+/).pop().replace(/:[\w-]+(\([^)]*\))?/g, '');
      const cls = last.match(/\.[\w-]+/g);
      if (cls) out.add(cls[cls.length - 1].slice(1));
    }
  }
  out.delete('pt');
  return [...out].sort();
}

// the classes whose painting rules read the sky-clock variables (light, sun, moon): home.js sets
// those variables on these elements only — set on the .pt root, every change would restyle all ~12,000 shapes
export const CLOCK_VARS = ['pd', 'ps', 'pk', 'pn', 'mono', 'sunx', 'suny', 'monx', 'mony', 'flyy', 'dawn', 'sune', 'ghost'];
export function lit(designHtml) {
  const css = between(designHtml, '/*PAINT*/', '/*/PAINT*/').replace(/@keyframes[^{]*\{([^{}]*\{[^}]*\})*[^}]*\}/g, '');
  const uses = new RegExp('var\\(--(' + CLOCK_VARS.join('|') + ')[,)]');
  const out = new Set();
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    if (!uses.test(m[2])) continue;
    for (const sel of m[1].replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*@media[^{]*/, '').split(',')) {
      const last = sel.trim().split(/\s+/).pop().replace(/::?[\w-]+(\([^)]*\))?/g, '');
      const cls = last.match(/\.[\w-]+/g);
      if (!cls) throw new Error('clock variable read by a selector without a class: ' + sel.trim());
      out.add(cls[cls.length - 1].slice(1));
    }
  }
  out.delete('pt');
  return [...out].sort();
}

export function skins(designHtml) {
  return JSON.parse(between(designHtml, '/*SKINDATA*/', '/*/SKINDATA*/'));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = readFileSync('design/Main.dc.html', 'utf8');
  const out = build(src);
  writeFileSync('sky.js',
    '// GENERATED by scripts/build-sky.mjs from design/Main.dc.html (the Eiffel Tower painting + the skins\' moments and firework shapes); home.js injects it into .sky.\n' +
    '// A script rather than a fetched fragment so it also loads from file://.\n' +
    'window.SKY_SVG = ' + JSON.stringify(out) + ';\n' +
    'window.SKY_SK = ' + JSON.stringify(skins(src)) + ';\n' +
    'window.SKY_TOGGLES = ' + JSON.stringify(toggles(src)) + ';\n' +
    'window.SKY_LIT = ' + JSON.stringify(lit(src)) + ';\n');
  console.log('sky.js:', out.length, 'bytes');
}
